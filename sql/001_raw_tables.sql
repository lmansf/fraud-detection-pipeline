-- Raw (bronze) landing tables in Supabase for the Owl Park order generator.
-- Every column except id/created_at is nullable on purpose: raw never rejects a row.

create table if not exists public.raw_transactions (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  source_system text default 'checkout_api',
  batch_id uuid,
  raw_payload jsonb,
  transaction_id uuid,
  request_id uuid,
  cart_id uuid,
  session_id uuid,
  event_ts timestamptz,
  guest_id uuid,
  is_guest_checkout boolean,
  account_created_at timestamptz,
  email text,
  phone text,
  channel text,
  device_id text,
  ip_address inet,
  ip_country text,
  user_agent text,
  payment_token text,
  card_bin text,
  card_last4 text,
  card_expiry text,
  billing_name text,
  billing_country text,
  billing_postal text,
  currency text default 'USD',
  subtotal numeric,
  discount numeric,
  tax numeric,
  total numeric,
  promo_code text,
  cart jsonb,
  status text
);

create table if not exists public.raw_fraud_decisions (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  source_system text default 'fraud_scoring',
  batch_id uuid,
  raw_payload jsonb,
  decision_id uuid,
  transaction_id uuid,
  request_id uuid,
  decided_at timestamptz,
  score float8,
  decision text,
  reason_codes jsonb,
  model_version text,
  model_latency_ms float8,
  features_json jsonb
);

create table if not exists public.raw_checkout_responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  source_system text default 'checkout_api',
  batch_id uuid,
  raw_payload jsonb,
  response_id uuid,
  transaction_id uuid,
  request_id uuid,
  request_received_at timestamptz,
  response_sent_at timestamptz,
  response_status text,
  customer_message_code text,
  total_latency_ms float8,
  fraud_scoring_ms float8,
  payment_auth_ms float8,
  fraud_timeout boolean default false,
  fallback_used boolean default false,
  fallback_policy text,
  channel text,
  model_version text
);

create table if not exists public.raw_fraud_truth (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  source_system text default 'generator',
  batch_id uuid,
  raw_payload jsonb,
  transaction_id uuid,
  is_fraud boolean,
  fraud_pattern text,
  fraud_ring_id uuid,
  label_available_at timestamptz,
  generated_at timestamptz default now()
);

-- Supabase exposes tables through its public API; RLS with no policies limits access to the service role.
alter table public.raw_transactions enable row level security;
alter table public.raw_fraud_decisions enable row level security;
alter table public.raw_checkout_responses enable row level security;
alter table public.raw_fraud_truth enable row level security;

create index if not exists raw_transactions_created_at_idx on public.raw_transactions (created_at);
create index if not exists raw_fraud_decisions_created_at_idx on public.raw_fraud_decisions (created_at);
create index if not exists raw_checkout_responses_created_at_idx on public.raw_checkout_responses (created_at);
create index if not exists raw_fraud_truth_created_at_idx on public.raw_fraud_truth (created_at);
